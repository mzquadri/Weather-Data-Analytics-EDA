"""Compute the analysis summary that the README quotes, and the checks behind it.

    python -m src.summary

The repository already produced twelve figures and a small findings file. What it
did not do was ask whether the differences it reported were large enough to be
differences at all, or whether the aggregations behind them compare like with
like. Three of its statements do not survive that question, and the answers are
recorded here rather than asserted.

The wind speeds are generated by one formula with no city term, so the "windiest
city" is whichever of six identical distributions drew highest. The size of that
lead is measured against its standard error below.

Monthly precipitation totals are compared across months of different lengths, and
across a record whose final December is two days short, so a per-day rate is
computed alongside the total.

The correlation matrix pools six cities with different baselines, which mixes
between-city differences into a within-city relationship. The pooled, within-city
and within-city-and-month values are all recorded.

Writes results/summary.json.
"""

from __future__ import annotations

import argparse
import json
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results" / "summary.json"
DATA = ROOT / "data" / "weather_data.csv"

MEASUREMENTS = {
    "temp_mean_c": ("daily mean temperature", "degrees Celsius", "mean"),
    "temp_max_c": ("daily maximum temperature", "degrees Celsius", "mean"),
    "temp_min_c": ("daily minimum temperature", "degrees Celsius", "mean"),
    "precipitation_mm": ("daily precipitation", "millimetres", "sum"),
    "humidity_pct": ("relative humidity", "percent", "mean"),
    "wind_speed_ms": ("wind speed", "metres per second", "mean"),
    "pressure_hpa": ("air pressure", "hectopascals", "mean"),
    "cloud_cover_pct": ("cloud cover", "percent", "mean"),
    "uv_index": ("UV index", "index, 0 to 12", "mean"),
}


def load() -> pd.DataFrame:
    if not DATA.is_file():
        from .generate_data import generate_weather_data
        frame = generate_weather_data()
        DATA.parent.mkdir(parents=True, exist_ok=True)
        frame.to_csv(DATA, index=False)
        return frame
    return pd.read_csv(DATA, parse_dates=["date"])


def coverage(frame: pd.DataFrame) -> dict:
    """What the record actually covers, rather than what it is called.

    The generator asks for ten years as 3,650 days. Two of those years are leap
    years, so the record stops on 29 December 2023 and the final December is two
    days short of the others.
    """
    days = frame["date"].nunique()
    per_year = frame[frame["city"] == frame["city"].iloc[0]].groupby(
        frame["date"].dt.year).size()
    complete = {int(year): int(count) for year, count in per_year.items()}
    expected = {year: 366 if year % 4 == 0 else 365 for year in complete}
    short = {year: expected[year] - count
             for year, count in complete.items() if count != expected[year]}

    gaps = pd.Series(sorted(frame["date"].unique())).diff().dt.days.dropna()
    return {
        "rows": len(frame),
        "cities": int(frame["city"].nunique()),
        "columns": int(frame.shape[1]),
        "first_date": str(frame["date"].min().date()),
        "last_date": str(frame["date"].max().date()),
        "distinct_days": int(days),
        "days_per_year": complete,
        "years_short_of_a_full_calendar_year": short,
        "largest_gap_between_consecutive_days": int(gaps.max()) if len(gaps) else 0,
        "duplicate_city_date_pairs": int(frame.duplicated(["city", "date"]).sum()),
        "note": "the generator requests n_years * 365 days, which ignores leap "
                "days, so a record labelled ten years ends two days early",
    }


def schema(frame: pd.DataFrame) -> list[dict]:
    """Every measurement column with its unit, range and missingness."""
    out = []
    for name, (meaning, unit, aggregation) in MEASUREMENTS.items():
        column = frame[name]
        out.append({
            "name": name,
            "meaning": meaning,
            "unit": unit,
            "dtype": str(column.dtype),
            "missing": int(column.isna().sum()),
            "minimum": round(float(column.min()), 2),
            "maximum": round(float(column.max()), 2),
            "aggregates_by": aggregation,
            "derived": False,
        })
    return out


def city_statistics(frame: pd.DataFrame) -> dict:
    """Per-city figures, each aggregated the way its quantity requires."""
    out = {}
    for city, block in frame.groupby("city"):
        years = block["date"].dt.year.nunique()
        out[city] = {
            "latitude": float(block["latitude"].iloc[0]),
            "hemisphere": "northern" if block["latitude"].iloc[0] >= 0 else "southern",
            "days": len(block),
            "mean_temperature_c": round(float(block["temp_mean_c"].mean()), 2),
            "temperature_standard_deviation_c": round(
                float(block["temp_mean_c"].std()), 2),
            "coldest_day_c": round(float(block["temp_min_c"].min()), 1),
            "hottest_day_c": round(float(block["temp_max_c"].max()), 1),
            "total_precipitation_mm": round(float(block["precipitation_mm"].sum()), 1),
            "mean_annual_precipitation_mm": round(
                float(block["precipitation_mm"].sum() / years), 1),
            "wettest_day_mm": round(float(block["precipitation_mm"].max()), 1),
            "dry_day_share": round(
                float((block["precipitation_mm"] <= 0.05).mean()), 4),
            "mean_humidity_pct": round(float(block["humidity_pct"].mean()), 2),
            "mean_wind_speed_ms": round(float(block["wind_speed_ms"].mean()), 3),
        }
    return out


def wind_is_not_a_city_difference(frame: pd.DataFrame) -> dict:
    """Is the windiest city windier than the next, or just luckier?

    The generator gives every city the same wind formula, differing only in
    seasonal phase, so any ranking here is a draw from six identical
    distributions. The lead is reported in standard errors so that is visible.
    """
    grouped = frame.groupby("city")["wind_speed_ms"]
    summary = grouped.agg(["mean", "std", "count"])
    summary["standard_error"] = summary["std"] / np.sqrt(summary["count"])

    ranked = summary["mean"].sort_values(ascending=False)
    first, second = ranked.index[0], ranked.index[1]
    difference = float(ranked.iloc[0] - ranked.iloc[1])
    combined = float(np.sqrt(summary.loc[first, "standard_error"] ** 2
                             + summary.loc[second, "standard_error"] ** 2))

    return {
        "highest_mean": first,
        "second_highest": second,
        "difference_ms": round(difference, 4),
        "combined_standard_error_ms": round(combined, 4),
        "difference_in_standard_errors": round(difference / combined, 2),
        "spread_across_all_cities_ms": round(
            float(ranked.iloc[0] - ranked.iloc[-1]), 4),
        "per_city_mean_ms": {city: round(float(value), 3)
                             for city, value in ranked.items()},
        "verdict": "the generator applies one wind formula to every city, with no "
                   "city term, so this ranking is noise and not a property of any "
                   "city",
    }


def monthly_precipitation(frame: pd.DataFrame) -> dict:
    """Totals and per-day rates, because months are not the same length.

    A raw monthly total compares February against January over two fewer days,
    and in this record December is shorter still.
    """
    totals = frame.groupby("month")["precipitation_mm"].sum()
    observations = frame.groupby("month").size()
    rate = totals / observations

    # Which months change position when the two orderings are compared. The
    # distortion is systematic, but it only reorders months whose totals are
    # already close together, so this list is the honest measure of its reach.
    by_total = list(totals.sort_values(ascending=False).index)
    by_rate = list(rate.sort_values(ascending=False).index)
    moved = sorted(int(m) for m in totals.index
                   if by_total.index(m) != by_rate.index(m))

    return {
        "total_mm_by_month": {int(m): round(float(v), 1) for m, v in totals.items()},
        "observations_by_month": {int(m): int(v) for m, v in observations.items()},
        "mm_per_day_by_month": {int(m): round(float(v), 4) for m, v in rate.items()},
        "wettest_month_by_total": int(totals.idxmax()),
        "wettest_month_by_rate": int(rate.idxmax()),
        "driest_month_by_total": int(totals.idxmin()),
        "driest_month_by_rate": int(rate.idxmin()),
        "months_that_change_rank": moved,
        "example_of_the_difference": {
            "january_total_mm": round(float(totals[1]), 1),
            "february_total_mm": round(float(totals[2]), 1),
            "january_observed_days": int(observations[1]),
            "february_observed_days": int(observations[2]),
            "january_mm_per_day": round(float(rate[1]), 4),
            "february_mm_per_day": round(float(rate[2]), 4),
            "february_total_relative_to_january_pct": round(
                float((totals[2] / totals[1] - 1) * 100), 1),
            "february_rate_relative_to_january_pct": round(
                float((rate[2] / rate[1] - 1) * 100), 1),
            "reading": "February totals less than January and rains more per day; "
                       "the total is lower only because the month is shorter",
        },
    }


def correlation_levels(frame: pd.DataFrame, first: str, second: str) -> dict:
    """The same correlation computed at three levels of pooling."""
    def r(block):
        if len(block) < 3:
            return np.nan
        return float(np.corrcoef(block[first], block[second])[0, 1])

    def slope(block):
        return float(np.polyfit(block[first], block[second], 1)[0])

    pooled = r(frame)
    per_city = frame.groupby("city").apply(r, include_groups=False)
    per_city_month = frame.groupby(["city", "month"]).apply(r, include_groups=False)
    city_slopes = frame.groupby("city").apply(slope, include_groups=False)

    return {
        "pair": f"{first} against {second}",
        "pooled_across_cities": round(pooled, 3),
        "within_city_mean": round(float(per_city.mean()), 3),
        "within_city_and_month_mean": round(float(per_city_month.mean()), 3),
        "per_city": {city: round(float(value), 3)
                     for city, value in per_city.items()},
        # The regression slope makes the same point in the units of the data:
        # the pooled line is steeper than every city's own line.
        "pooled_slope": round(slope(frame), 3),
        "steepest_city_slope": round(float(city_slopes.min()), 3),
        "shallowest_city_slope": round(float(city_slopes.max()), 3),
        "per_city_slope": {city: round(float(value), 3)
                           for city, value in city_slopes.items()},
        "note": "pooling mixes differences between cities into a relationship that "
                "is meant to describe days within one city",
    }


def extremes(frame: pd.DataFrame) -> dict:
    """Selected by rule from the record, not chosen by eye."""
    hottest = frame.loc[frame["temp_max_c"].idxmax()]
    coldest = frame.loc[frame["temp_min_c"].idxmin()]
    wettest = frame.loc[frame["precipitation_mm"].idxmax()]
    windiest = frame.loc[frame["wind_speed_ms"].idxmax()]

    def entry(row, column):
        return {"city": row["city"], "date": str(row["date"].date()),
                "value": round(float(row[column]), 1)}

    dry_spells = []
    for city, block in frame.groupby("city"):
        ordered = block.sort_values("date")
        dry = (ordered["precipitation_mm"] <= 0.05).to_numpy()
        longest, current = 0, 0
        for value in dry:
            current = current + 1 if value else 0
            longest = max(longest, current)
        dry_spells.append({"city": city, "longest_dry_run_days": int(longest)})

    return {
        "hottest_day": entry(hottest, "temp_max_c"),
        "coldest_day": entry(coldest, "temp_min_c"),
        "wettest_day": entry(wettest, "precipitation_mm"),
        "windiest_day": entry(windiest, "wind_speed_ms"),
        "longest_dry_runs": sorted(dry_spells,
                                   key=lambda e: -e["longest_dry_run_days"]),
    }


def uv_floor(frame: pd.DataFrame) -> dict:
    """How often the UV index sits at zero, which is a generator artifact.

    The generator clips a sine to be non-negative, so UV is exactly zero for
    roughly half of every year outside the tropics. Real winter UV is low but not
    zero, so the UV figure describes the clipping and not a season.
    """
    at_floor = {}
    for city, block in frame.groupby("city"):
        at_floor[city] = round(float((block["uv_index"] <= 0.05).mean()), 4)
    return {
        "share_of_days_at_or_below_0.05": at_floor,
        "note": "np.clip(sin(...), 0, 1) in the generator produces a hard floor "
                "for half the year away from the equator; real winter UV is low "
                "rather than absent",
    }


def build() -> dict:
    frame = load()
    return {
        "generated_utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "source": "generated by src/generate_data.py, seed 42; not observations",
        "coverage": coverage(frame),
        "schema": schema(frame),
        "cities": city_statistics(frame),
        "wind_ranking": wind_is_not_a_city_difference(frame),
        "monthly_precipitation": monthly_precipitation(frame),
        "temperature_humidity": correlation_levels(
            frame, "temp_mean_c", "humidity_pct"),
        "temperature_pressure": correlation_levels(
            frame, "temp_mean_c", "pressure_hpa"),
        "extremes": extremes(frame),
        "uv_index_floor": uv_floor(frame),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=OUT)
    arguments = parser.parse_args()

    result = build()
    arguments.out.parent.mkdir(parents=True, exist_ok=True)
    arguments.out.write_text(json.dumps(result, indent=2) + "\n",
                             encoding="utf-8", newline="\n")

    cover = result["coverage"]
    print(f"  {cover['rows']:,} rows, {cover['cities']} cities, "
          f"{cover['first_date']} to {cover['last_date']}")
    print(f"  years short of a full calendar year: "
          f"{cover['years_short_of_a_full_calendar_year']}")

    wind = result["wind_ranking"]
    print(f"\n  wind: {wind['highest_mean']} leads {wind['second_highest']} by "
          f"{wind['difference_ms']} m/s, which is "
          f"{wind['difference_in_standard_errors']} standard errors")

    precipitation = result["monthly_precipitation"]
    print(f"  precipitation: wettest month is {precipitation['wettest_month_by_total']} "
          f"by total and {precipitation['wettest_month_by_rate']} by rate per day")

    humidity = result["temperature_humidity"]
    print(f"  temperature against humidity: pooled "
          f"{humidity['pooled_across_cities']}, within city "
          f"{humidity['within_city_mean']}, within city and month "
          f"{humidity['within_city_and_month_mean']}")

    print(f"\n  wrote {arguments.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
